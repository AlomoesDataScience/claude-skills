"""SCBM (or any mod's) spell changes, read from a dom6-modinspector output folder.

  python3 -I spellchanges.py build [DATA] [OUT.md]   every new/changed spell -> a markdown table by school and level
                                                    (DATA default ../data/inspector, OUT default ../spell-changes.md)
  python3 -I spellchanges.py paths E2N2G1H2 [--max-level N] [--school Alt] [--real] [DATA]
                                                    the changed/new spells a mage with these paths can cast
Rebuild DATA after a new SCBM version: dom6-modinspector inspect_mod.py <mod.dm> --out DATA.
Run with no arguments = this text.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEF_DATA = os.path.join(HERE, "..", "data", "inspector")
AI_KEYS = {"aispellmod", "aiassmod", "ainocast", "aibadlvl", "aisinglerec"}
NOISE = {"aoe", "range", "research", "effects_count", "descr", "uwok", "pathlevel1", "pathlevel2", "path1", "path2",
         "effect", "internal", "nationname"}
ORDER = ["Conjuration", "Alteration", "Evocation", "Construction", "Enchantment", "Thaumaturgy", "Blood", "Divine"]


def load(data):
    txt = open(os.path.join(data, "mod_pages.txt"), encoding="utf-8").read()
    recs = []
    for block in re.split(r"\n(?==== )", txt):
        m = re.match(r"=== spell (\S+): (.*)", block)
        if not m:
            continue
        tag = "new" if "\n[new]" in block else "changed" if "\n[changed]" in block else None
        if not tag:
            continue
        lines = block.split("\n")
        diff = []
        if "changed from vanilla:" in block:
            for l in block.split("changed from vanilla:")[1].split("\n")[1:]:
                if not l.startswith("  "):
                    break
                diff.append(l.strip())
        g = lambda k: (re.search(r"\[" + k + r"\]: (.*)", block) or [None, ""])[1].strip()
        school, lvl = (lines[1].strip().rsplit(" ", 1) + ["?"])[:2] if len(lines) > 1 else ("?", "?")
        recs.append({"id": m.group(1), "name": m.group(2).strip(), "tag": tag, "school": school, "level": lvl,
                     "kind": lines[3].strip() if len(lines) > 3 else "", "path": lines[4].strip() if len(lines) > 4 else "",
                     "range": g("rng_bat"), "aoe": g("aoe_s"), "fat": g("fatiguecost"), "prec": g("precision"),
                     "diff": diff, "desc": ((re.search(r"\ndescription: (.*)", block) or [None, ""])[1].strip()
                     or " ".join(re.findall(r'#details "([^"]*)', block)))})
    return recs


def kind_of(r):
    if r["tag"] == "new":
        return "new"
    keys = {d.split(":")[0] for d in r["diff"]}
    return "AI only" if keys and keys <= AI_KEYS else "real"


def short(r):
    out = []
    for d in r["diff"]:
        k = d.split(":")[0]
        if k in NOISE or k == "description":
            continue
        out.append(d.replace(" -> ", "→"))
    return "; ".join(out)[:260]


def can_cast(path, paths):
    have = dict((p, int(n)) for p, n in re.findall(r"([FAWESDNGBH])(\d+)", paths))
    need = re.findall(r"([FAWESDNGBH])(\d+)", path)
    return bool(need) and all(have.get(p, 0) >= int(n) for p, n in need)


def table(rows):
    o = ["| Spell | School | Lvl | Path | Kind | Rng | Area | Fat | Prec | What SCBM changed |", "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        what = "NEW: " + r["desc"][:140] if r["tag"] == "new" else short(r)
        o.append(f"| {r['name']} | {r['school'][:5]} | {r['level']} | {r['path']} | {r['kind']} | {r['range']} | {r['aoe']} | {r['fat']} | "
                 f"{r['prec']} | {what.replace('|', '/')} |")
    return o


def sort_key(r):
    s = next((i for i, x in enumerate(ORDER) if r["school"].startswith(x[:5])), 99)
    return (s, int(r["level"]) if r["level"].isdigit() else 99, r["name"])


def build(data, out):
    recs = sorted(load(data), key=sort_key)
    n = {k: sum(kind_of(r) == k for r in recs) for k in ("new", "real", "AI only")}
    o = [f"# SCBM spell changes (generated by scripts/spellchanges.py from data/inspector; {len(recs)} spells)", "",
         f"{n['new']} new, {n['real']} with real changes, {n['AI only']} with AI cast weights only (listed last).",
         "Diff = vanilla→SCBM. Range/area/fatigue columns are the SCBM values. Fatigue `-` suffix = less with skill.", ""]
    for sch in ORDER + ["Other"]:
        rows = [r for r in recs if kind_of(r) != "AI only" and
                (r["school"].startswith(sch[:5]) or (sch == "Other" and not any(r["school"].startswith(x[:5]) for x in ORDER)))]
        if rows:
            o += [f"## {sch}", ""] + table(rows) + [""]
    ai = [r for r in recs if kind_of(r) == "AI only"]
    o += ["## AI cast weights only (the AI casts these more or less on its own; script what it avoids)", ""]
    o += [", ".join(f"{r['name']} ({short(r)})" for r in ai), ""]
    open(out, "w").write("\n".join(o))
    print(f"{len(recs)} spells -> {out}")


def main(a):
    if not a or a[0] in ("-h", "--help"):
        sys.exit(__doc__)
    if a[0] == "build":
        data = a[1] if len(a) > 1 else DEF_DATA
        build(data, a[2] if len(a) > 2 else os.path.join(HERE, "..", "spell-changes.md"))
    elif a[0] == "paths":
        paths = a[1]
        mx = int(a[a.index("--max-level") + 1]) if "--max-level" in a else 9
        sch = a[a.index("--school") + 1] if "--school" in a else ""
        pos = [x for i, x in enumerate(a[2:], 2) if not x.startswith("--") and a[i - 1] not in ("--max-level", "--school")]
        recs = sorted(load(pos[0] if pos else DEF_DATA), key=sort_key)
        rows = [r for r in recs if can_cast(r["path"], paths) and (not r["level"].isdigit() or int(r["level"]) <= mx)
                and r["school"].startswith(sch) and ("--real" not in a or kind_of(r) != "AI only")]
        print("\n".join(table(rows)))
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv[1:])
