#!/usr/bin/env python3
"""Look up World of Greyhawk lore in the local wiki copy (Worlds/Greyhawk/lore/).

  lore.py realm NAME            a realm's fact box (ruler, capital, towns, population, peoples,
                                religions, allies, enemies, resources); NAME may be part of a title
  lore.py page NAME [--lines N] a page's text (article body)
  lore.py search REGEX [--n 40] matching lines across all pages, with the page name
  lore.py list [--region TEXT]  every realm: region, capital, population
  lore.py table OUT.md          write the realm table (realms.md in this skill)
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DND = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(HERE))))   # Dungeons & Dragons/
LORE = os.path.join(DND, "Worlds", "Greyhawk", "lore")
PAGES = os.path.join(LORE, "pages")


def boxes():
    return json.load(open(os.path.join(LORE, "infoboxes.json")))


def find(name, titles):
    k = name.replace(" ", "_").lower()
    exact = [t for t in titles if t.lower() == k]
    part = [t for t in titles if k in t.lower()]
    if exact:
        return exact[0]
    if len(part) == 1:
        return part[0]
    sys.exit(f"{name!r}: " + (f"several matches: {', '.join(part)}" if part else "no such page"))


def pop(v):
    m = re.search(r"[\d,]{3,}", v.get("Population", ""))
    return int(m.group(0).replace(",", "")) if m else 0


def realm(name):
    b = boxes()
    t = find(name, [k for k, v in b.items() if v])
    print(f"== {t.replace('_', ' ')}")
    for k, v in b[t].items():
        print(f"{k}: {v}")


def page(name, lines=80):
    titles = [f[:-4] for f in os.listdir(PAGES) if f.endswith(".txt")] + ["Flanaess"]
    t = find(name, titles)
    p = os.path.join(LORE, "Flanaess.txt") if t == "Flanaess" else os.path.join(PAGES, t + ".txt")
    txt = open(p).read().split("\n### Bibliography")[0].split("\n## References")[0]
    print("\n".join(txt.splitlines()[:lines]))


def search(rx, n=40):
    r = re.compile(rx, re.I)
    hits = 0
    for f in sorted(os.listdir(PAGES)):
        if not f.endswith(".txt"):
            continue
        body = open(os.path.join(PAGES, f)).read().split("\n## References")[0]
        for line in body.splitlines():
            if line.startswith(("|", "id=")):     # fact-box rows, page chrome
                continue
            if r.search(line):
                print(f"{f[:-4]}: {line.strip()[:200]}")
                hits += 1
                if hits >= n:
                    return


def rows(region=None):
    b = boxes()
    out = []
    for t, v in sorted(b.items()):
        if "Capital" in v or "Ruler" in v:
            if region and region.lower() not in v.get("Region", "").lower():
                continue
            out.append((t.replace("_", " "), v.get("Region", "-"), v.get("Capital", "-"), pop(v), v))
    return out


def main(a):
    if not a or a[0] in ("-h", "--help"):
        print(__doc__)
        return
    opt = lambda k, d: a[a.index(k) + 1] if k in a else d
    if a[0] == "realm":
        realm(" ".join(x for x in a[1:]))
    elif a[0] == "page":
        page(a[1], int(opt("--lines", 80)))
    elif a[0] == "search":
        search(a[1], int(opt("--n", 40)))
    elif a[0] == "list":
        for t, reg, cap, p, _ in rows(opt("--region", None)):
            print(f"{t:38} {reg[:28]:28} {cap[:24]:24} {p:>10,}")
    elif a[0] == "table":
        L = ["# Realms of the Flanaess (from the wiki's fact boxes)", "",
             "Generated by `scripts/lore.py table`; facts as the wiki states them (setting date varies by page,",
             "mostly 576-591 CY). Main people = the largest group listed.", "",
             "| Realm | Region | Capital | Population | Main people | Resources |", "|---|---|---|---|---|---|"]
        for t, reg, cap, p, v in rows():
            races = re.sub(r"\s*\(.*?\)", "", v.get("Races", "")).split(",")[0].strip()
            res = v.get("Resources", "-")
            L.append(f"| {t} | {reg} | {cap} | {p:,} | {races[:40] or '-'} | {res[:60]} |".replace(" 0 |", " - |"))
        open(a[1], "w").write("\n".join(L) + "\n")
        print(len(L) - 7, "realms ->", a[1])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv[1:])
