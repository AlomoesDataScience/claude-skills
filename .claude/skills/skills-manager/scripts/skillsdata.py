"""Skills data: write a catalogue of every skill and a coverage review of the workspace.

The user (2026-11-15): "make a skills data folder, and start documenting everything you use as skills and
why ... a review of what is properly skilled out would be good."

usage:
  python3 -I skillsdata.py catalogue     write Skills Data/CATALOGUE.md (every skill: where, what, why, scripts)
  python3 -I skillsdata.py coverage      write Skills Data/COVERAGE.md (which folders have skills, which don't)
  python3 -I skillsdata.py all           both

Read only apart from those two files. "Why" is the first line in SKILL.md that quotes the user with a date
(the Origin), or "no origin line" when the skill has none (a gap to fix).
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))


def workspace():
    d = HERE
    while d != "/":
        if os.path.exists(os.path.join(d, "BACKLOG.md")):
            return d
        d = os.path.dirname(d)
    sys.exit("workspace (BACKLOG.md) not found")


SKIP = {".git", "node_modules", "__pycache__", "repos", "wiki", "illwiki", "Archive", "Archived", ".venv"}


def find_skills(ws):
    out = []
    for root, dirs, files in os.walk(ws):
        dirs[:] = [d for d in dirs if d not in SKIP and not (d.startswith(".") and d != ".claude")]
        if "SKILL.md" in files and os.path.basename(os.path.dirname(root)) == "skills":
            out.append(os.path.join(root, "SKILL.md"))
    return sorted(out)


def front(text):
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    meta = {}
    if m:
        for line in m.group(1).splitlines():
            k, _, v = line.partition(":")
            meta[k.strip()] = v.strip().strip('"')
    return meta, text[m.end():] if m else text


def origin(body):
    for line in body.splitlines():
        if re.search(r"the user[^.\n]{0,40}\(?20\d\d-\d\d-\d\d", line) and '"' in line:
            return line.strip()[:220]
    for line in body.splitlines():
        if re.search(r"the user.{0,40}20\d\d-\d\d-\d\d", line):
            return line.strip()[:220]
    return ""


def owner(ws, path):
    """The folder the skill belongs to: '(root)' or the folder holding .claude/skills."""
    rel = os.path.relpath(path, ws)
    head = rel.split("/.claude/skills/")[0]
    return "(root)" if head.startswith(".claude/skills") else head


def load(ws):
    rows = []
    for p in find_skills(ws):
        text = open(p, encoding="utf-8", errors="replace").read()
        meta, body = front(text)
        d = os.path.dirname(p)
        sd = os.path.join(d, "scripts")
        scripts = sorted(f for f in os.listdir(sd) if f.endswith(".py")) if os.path.isdir(sd) else []
        rows.append(dict(name=meta.get("name", os.path.basename(d)), desc=meta.get("description", ""),
                         owner=owner(ws, p), lines=text.count("\n"), why=origin(body), scripts=scripts))
    return rows


def catalogue(ws):
    rows = load(ws)
    groups = {}
    for r in rows:
        groups.setdefault(r["owner"], []).append(r)
    noorigin = [r["name"] for r in rows if not r["why"]]
    out = ["# Skill catalogue", "",
           "Generated by `skills-manager/scripts/skillsdata.py catalogue`; edit the SKILL.md files, not this.",
           f"{len(rows)} skills in {len(groups)} places. What = the description; Why = the Origin line "
           "(the user's words). Routing lives in `.claude/skills/INDEX.md`.", ""]
    if noorigin:
        out += [f"**No origin line ({len(noorigin)}):** " + ", ".join(noorigin), ""]
    for g in sorted(groups, key=lambda k: (k != "(root)", k)):
        out += [f"## {g}", ""]
        for r in sorted(groups[g], key=lambda r: r["name"]):
            s = f" Scripts: {', '.join(r['scripts'])}." if r["scripts"] else ""
            out.append(f"- **{r['name']}** ({r['lines']} lines). {r['desc']}{s}")
            out.append(f"  - Why: {r['why'] or 'no origin line'}")
        out.append("")
    return "\n".join(out)


def areas(ws):
    """Folders that should each have skills: games, projects, IPs, theory shelves."""
    res = []
    g = os.path.join(ws, "Games")
    for genre in sorted(os.listdir(g)):
        gp = os.path.join(g, genre)
        if not os.path.isdir(gp):
            continue
        for game in sorted(os.listdir(gp)):
            if os.path.isdir(os.path.join(gp, game)) and not game.startswith("."):
                res.append(("Games", f"Games/{genre}/{game}"))
    for grp in ("Projects/Our Games", "Projects/Stuff I made", "Projects/Game Dev Stuff",
                "Projects/Other Projects", "IPs"):
        p = os.path.join(ws, grp)
        if os.path.isdir(p):
            for x in sorted(os.listdir(p)):
                if os.path.isdir(os.path.join(p, x)) and not x.startswith("."):
                    res.append((grp.split("/")[-1], f"{grp}/{x}"))
    for shelf in ("Theory/Sources/Military Theory", "Theory/Sources/Economic Theory", "Theory/Sources/Political Theory",
                  "Theory/Derived"):  # moved 2026-11-15
        if os.path.isdir(os.path.join(ws, shelf)):
            res.append(("Theory", shelf))
    return res


def size(p):
    n = 0
    for root, dirs, files in os.walk(p):
        dirs[:] = [d for d in dirs if d not in {".git", "node_modules", "repos"}]
        n += len(files)
    return n


def coverage(ws):
    rows = load(ws)
    owners = {}
    for r in rows:
        owners.setdefault(r["owner"], []).append(r["name"])
    out = ["# Skill coverage", "",
           "Generated by `skills-manager/scripts/skillsdata.py coverage`. A folder counts as skilled when it "
           "holds its own `.claude/skills/`, or a skill under a parent folder covers it. Files = files in the "
           "folder (a rough size). The user decides what is worth a skill; empty folders are placeholders.", ""]
    texts = {}
    for p in find_skills(ws):
        t = open(p, encoding="utf-8", errors="replace").read()
        texts[front(t)[0].get("name", os.path.basename(os.path.dirname(p)))] = t
    stats = {}
    lines = {}
    for kind, a in areas(ws):
        own = [n for o, ns in owners.items() for n in ns
               if o == a or a.startswith(o + "/") or o.startswith(a + "/")]
        base = os.path.basename(a)
        named = [r["name"] for r in rows if r["owner"] == "(root)" and base in texts[r["name"]]]
        n = size(os.path.join(ws, a))
        state = "skilled" if own else ("empty" if n == 0 else ("named only" if named else "NO SKILL"))
        stats.setdefault(kind, {}).setdefault(state, 0)
        stats[kind][state] += 1
        lines.setdefault(kind, []).append(
            f"| {a.split('/', 1)[-1] if kind == 'Games' else a} | {state} | {n} | {', '.join(sorted(own)[:6])}"
            f"{' ...' if len(own) > 6 else ''} | {', '.join(named[:4])}{' ...' if len(named) > 4 else ''} |")
    out += ["## Summary", "", "| Area | skilled | named only | no skill | empty |", "|---|---|---|---|---|"]
    for k, v in stats.items():
        out.append(f"| {k} | {v.get('skilled', 0)} | {v.get('named only', 0)} | {v.get('NO SKILL', 0)} | {v.get('empty', 0)} |")
    out.append("")
    for k, ls in lines.items():
        out += [f"## {k}", "", "| Folder | State | Files | Own skills | Named in root skills |", "|---|---|---|---|---|"]
        out += sorted(ls, key=lambda l: (" skilled " in l, " empty " in l, l))
        out.append("")
    return "\n".join(out)


def main():
    if len(sys.argv) < 2 or sys.argv[1] not in {"catalogue", "coverage", "all"}:
        print(__doc__)
        return
    ws = workspace()
    d = os.path.join(ws, "Skills Data")
    os.makedirs(d, exist_ok=True)
    jobs = {"catalogue": [("CATALOGUE.md", catalogue)], "coverage": [("COVERAGE.md", coverage)]}
    jobs["all"] = jobs["catalogue"] + jobs["coverage"]
    for fn, f in jobs[sys.argv[1]]:
        open(os.path.join(d, fn), "w", encoding="utf-8").write(f(ws) + "\n")
        print("wrote", os.path.join("Skills Data", fn))


if __name__ == "__main__":
    main()
